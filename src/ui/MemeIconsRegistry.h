inline std::string normalizeIconName(const std::string &raw) {
    std::string out;
    out.reserve(raw.size() + 4);
    for (size_t i = 0; i < raw.size(); ++i) {
        unsigned char c = static_cast<unsigned char>(raw[i]);
        if (c == '_' || c == ' ') {
            if (!out.empty() && out.back() != '-') out.push_back('-');
        } else if (std::isupper(c)) {
            if (i > 0 && !out.empty() && out.back() != '-' && std::islower(static_cast<unsigned char>(raw[i - 1]))) {
                out.push_back('-');
            }
            out.push_back(static_cast<char>(std::tolower(c)));
        } else {
            out.push_back(static_cast<char>(std::tolower(c)));
        }
    }
    if (out == "close") return "x";
    if (out == "warn" || out == "warning") return "alert-triangle";
    if (out == "gear") return "settings";
    if (out == "doc" || out == "docs") return "book-open";
    if (out == "code2") return "code";
    return out;
}

inline std::string toPascalIconName(const std::string &kebab) {
    std::string out;
    bool cap = true;
    for (char c : kebab) {
        if (c == '-') {
            cap = true;
        } else {
            out.push_back(cap ? static_cast<char>(std::toupper(static_cast<unsigned char>(c))) : c);
            cap = false;
        }
    }
    return out;
}

